import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildAllScenarios } from '@jfm/ui-harness/scenarios';

/**
 * Produce the data the browser harness renders.
 *
 * The pipeline reads its recorded Jira fixtures from disk and runs in Node, so
 * it cannot execute in the browser. This script runs it once and writes the
 * resolver responses out as JSON — the same objects the resolver would return
 * over the bridge, produced by the same code path the test suites use.
 *
 * The output is generated, not authored: it is gitignored, and regenerated by
 * `pnpm run ui:screens`.
 */

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'harness', 'generated');

const scenarios = await buildAllScenarios();
const byId = Object.fromEntries(scenarios.map((scenario) => [scenario.id, scenario]));

mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, 'scenarios.json'), `${JSON.stringify(byId, null, 2)}\n`, 'utf8');

process.stdout.write(`wrote ${scenarios.length} scenarios to ${join(OUT, 'scenarios.json')}\n`);
